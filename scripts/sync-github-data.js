#!/usr/bin/env node
// Regenerates data/contributions.json + data/repos.json from the GitHub
// GraphQL API, and rebuilds assets/fallback.js (the offline snapshot the
// site dynamic-imports when live fetches fail). Run daily by
// .github/workflows/update-contributions.yml, or manually:
//   CONTRIB_PAT=... npm run sync

import fs from "node:fs";
import { fetchContributionCalendar, fetchTopRepos } from "./lib/github.js";
import { summarize } from "../assets/lib/stats.js";

const USERNAME = "nikhilpravinpise";
const TOKEN = process.env.CONTRIB_PAT || process.env.GITHUB_TOKEN;

if (!TOKEN) {
  console.error("Missing CONTRIB_PAT (or GITHUB_TOKEN) env var");
  process.exit(1);
}

const GENERATED_HEADER =
  "// GENERATED by scripts/sync-github-data.js - do not edit by hand.";

function writeJson(path, value) {
  fs.writeFileSync(path, JSON.stringify(value, null, 2) + "\n");
}

async function main() {
  const generatedAt = new Date().toISOString();

  const cal = await fetchContributionCalendar(TOKEN, USERNAME);
  const contributions = summarize(
    USERNAME,
    cal.totalContributions,
    cal.days,
    generatedAt,
  );

  const topRepos = await fetchTopRepos(TOKEN, USERNAME);
  const repos = {
    username: USERNAME,
    generated_at: generatedAt,
    user_created_at: cal.createdAt,
    repos: topRepos,
  };

  fs.mkdirSync("data", { recursive: true });
  fs.mkdirSync("assets", { recursive: true });
  writeJson("data/contributions.json", contributions);
  writeJson("data/repos.json", repos);
  console.log(
    `Wrote data/contributions.json (${contributions.total_contributions} contributions, ${contributions.days.length} days)`,
  );
  console.log(`Wrote data/repos.json (${repos.repos.length} repositories)`);

  // Offline snapshot, dynamic-imported by the site only when live fetches fail.
  const fallback =
    `${GENERATED_HEADER}\n` +
    `export const contributions = ${JSON.stringify(contributions)};\n` +
    `export const repos = ${JSON.stringify(repos)};\n`;
  fs.writeFileSync("assets/fallback.js", fallback);
  console.log("Rebuilt assets/fallback.js offline snapshot");

  // Machine-readable summary for the workflow step summary.
  if (process.env.GITHUB_STEP_SUMMARY) {
    fs.appendFileSync(
      process.env.GITHUB_STEP_SUMMARY,
      [
        "## Contribution data refresh",
        "",
        `- Total contributions: **${contributions.total_contributions}**`,
        `- Current streak: **${contributions.current_streak.length} days**`,
        `- Longest streak: **${contributions.longest_streak.length} days**`,
        `- Repos tracked: **${repos.repos.length}**`,
      ].join("\n") + "\n",
    );
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
